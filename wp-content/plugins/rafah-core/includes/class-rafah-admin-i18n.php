<?php
/**
 * Rafah Core — Dashboard localization.
 *
 * Makes the whole admin experience bilingual WITHOUT shipping compiled .mo
 * files: a single `gettext` filter maps our English source strings (text
 * domain "rafah") to Arabic whenever the logged-in employee's dashboard
 * language is Arabic. Set the dashboard language per user in
 * Users → Profile → Language (or site-wide in Settings → General).
 *
 * - Arabic dashboard  → Arabic labels everywhere (meta boxes, Units Manager…).
 * - English dashboard → the original English source strings.
 *
 * Front-end strings are unaffected here — they are served by rafah_text()
 * keyed off the Polylang page language. This layer is admin-only, so a
 * visitor's language never changes because of an employee's preference.
 *
 * To add a string: add its English source as the key and Arabic as the value
 * in map(). Anything missing simply falls back to English.
 *
 * @package Rafah_Core
 */

defined( 'ABSPATH' ) || exit;

class Rafah_Admin_I18n {

	public static function init() {
		add_filter( 'gettext', array( __CLASS__, 'translate' ), 10, 3 );
	}

	/**
	 * Translate a "rafah" domain string to Arabic in an Arabic dashboard.
	 *
	 * @param string $translation Current translation.
	 * @param string $text        Original (English) source string.
	 * @param string $domain      Text domain.
	 * @return string
	 */
	public static function translate( $translation, $text, $domain ) {
		if ( 'rafah' !== $domain || ! rafah_is_admin_context() || ! rafah_dashboard_is_ar() ) {
			return $translation;
		}

		$map = self::map();

		return $map[ $text ] ?? $translation;
	}

